function m(
  id: number,
  name: string,
  facId: string,
  uni: string,
  major: string,
  year: number,
  rating: string,
  sessions: number,
  price: number,
  city: string,
  tone: 1 | 2 | 3,
  next: string | null,
  bio: string,
  topics: string[],
): Mentor {
  const faculty = FACULTIES.find((f) => f.id === facId);
  if (!faculty) throw new Error(`Unknown faculty ${facId}`);
  return {
    id,
    name,
    facId,
    faculty: faculty.full,
    uni,
    major,
    year,
    rating,
    sessions,
    price,
    city,
    tone,
    available: next !== null,
    next: next ? `أقرب موعد: ${next}` : null,
    bio,
    topics,
  };
}

