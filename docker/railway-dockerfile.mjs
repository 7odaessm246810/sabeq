/**
 * Writes docker/api.railway.Dockerfile from docker/api.Dockerfile without the BuildKit cache mounts:
 * Railway's builder refuses cache ids that aren't prefixed with its service id ("Dockerfile failed
 * validation"). Everything else stays identical. Run after changing api.Dockerfile:
 *
 *   node docker/railway-dockerfile.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('./api.Dockerfile', import.meta.url);
const target = new URL('./api.railway.Dockerfile', import.meta.url);

const lines = readFileSync(source, 'utf8').split('\n');
const out = [];
for (const line of lines) {
  if (line.startsWith('# syntax=')) continue;
  // `RUN --mount=… \` → `RUN \`;  `    --mount=… \` (a continuation that is only a mount) → dropped.
  const cleaned = line.replace(/--mount=type=cache,\S+\s*/g, '');
  if (cleaned.trim() === '\\') continue;
  out.push(cleaned.replace(/^RUN\s+\\$/, 'RUN \\'));
}

const header = [
  '# GENERATED by docker/railway-dockerfile.mjs from docker/api.Dockerfile — do not edit by hand.',
  '# Same image, minus the BuildKit cache mounts that Railway refuses.',
  '#',
];
writeFileSync(target, [...header, ...out].join('\n'));
process.stdout.write(`wrote ${target.pathname}
`);
